import { useEffect, useRef, useState } from 'react';
import { useQuery } from '@tanstack/react-query';
import { useSearchParams } from 'react-router-dom';
import {
  FileBarChart,
  Printer,
  Play,
  BarChart3,
  FileText,
  Wallet,
  Receipt,
  Banknote,
  RotateCcw,
  Filter,
} from 'lucide-react';
import {
  getTiposReporte,
  generarReporte,
  exportReporteCsv,
  type ReporteGenerado,
  type ReporteFiltrosParams,
} from '@/services/reportes.service';
import { ReportPreview } from '@/components/reportes/ReportPreview';
import { PageListLayout } from '@/components/layout/PageListLayout';
import {
  SpreadsheetShell,
  SpreadsheetSection,
  SpreadsheetTitleActions,
  SpreadsheetReloadButton,
  spreadsheet,
} from '@/components/spreadsheet';
import { Select } from '@/components/ui/Select';
import { Alert } from '@/components/ui/Alert';
import { ApiClientError } from '@/services/api';

const ICONS: Record<string, typeof BarChart3> = {
  'resumen-ejecutivo': BarChart3,
  'ejecucion-presupuestaria': Wallet,
  expedientes: FileText,
  afectaciones: Receipt,
  libramientos: Receipt,
  pagos: Banknote,
};

const ESTADOS = [
  { value: '', label: 'Todos los estados' },
  { value: 'INICIADO', label: 'Iniciado' },
  { value: 'AFECTADO', label: 'Afectado' },
  { value: 'LIBRADO', label: 'Librado' },
  { value: 'PAGADO', label: 'Pagado' },
  { value: 'ARCHIVADO', label: 'Archivado' },
];

const MEDIOS = [
  { value: '', label: 'Todos los medios' },
  { value: 'EFECTIVO', label: 'Efectivo' },
  { value: 'TRANSFERENCIA', label: 'Transferencia' },
  { value: 'CHEQUE', label: 'Cheque' },
  { value: 'OTRO', label: 'Otro' },
];

const currentYear = String(new Date().getFullYear());

export function ReportesPage() {
  const printRef = useRef<HTMLDivElement>(null);
  const [searchParams, setSearchParams] = useSearchParams();

  const [tipoSeleccionado, setTipoSeleccionado] = useState(
    searchParams.get('tipo') || 'resumen-ejecutivo'
  );
  const [fechaDesde, setFechaDesde] = useState(searchParams.get('desde') ?? '');
  const [fechaHasta, setFechaHasta] = useState(searchParams.get('hasta') ?? '');
  const [anio, setAnio] = useState(searchParams.get('anio') ?? currentYear);
  const [estado, setEstado] = useState(searchParams.get('estado') ?? '');
  const [pagado, setPagado] = useState(searchParams.get('pagado') ?? '');
  const [medioPago, setMedioPago] = useState(searchParams.get('medio') ?? '');
  const [reporte, setReporte] = useState<ReporteGenerado | null>(null);
  const [loading, setLoading] = useState(false);
  const [exporting, setExporting] = useState(false);
  const [error, setError] = useState('');
  const [autoGenerated, setAutoGenerated] = useState(false);

  const { data: tipos, isFetching: loadingTipos, refetch: refetchTipos } = useQuery({
    queryKey: ['reportes-tipos'],
    queryFn: getTiposReporte,
  });

  const tipoActual = tipos?.find((t) => t.id === tipoSeleccionado);

  const buildFiltros = (): ReporteFiltrosParams => ({
    fechaDesde: fechaDesde || undefined,
    fechaHasta: fechaHasta || undefined,
    anio: anio ? Number(anio) : undefined,
    estado: estado || undefined,
    pagado: pagado === '' ? undefined : pagado === 'true',
    medioPago: medioPago || undefined,
  });

  const syncUrl = (tipo: string, filtros: ReporteFiltrosParams) => {
    const next = new URLSearchParams();
    next.set('tipo', tipo);
    if (filtros.fechaDesde) next.set('desde', filtros.fechaDesde);
    if (filtros.fechaHasta) next.set('hasta', filtros.fechaHasta);
    if (filtros.anio) next.set('anio', String(filtros.anio));
    if (filtros.estado) next.set('estado', filtros.estado);
    if (filtros.pagado !== undefined) next.set('pagado', String(filtros.pagado));
    if (filtros.medioPago) next.set('medio', filtros.medioPago);
    setSearchParams(next, { replace: true });
  };

  const handleGenerar = async (overrideTipo?: string) => {
    const tipo = overrideTipo ?? tipoSeleccionado;
    const filtros = buildFiltros();
    setError('');
    setLoading(true);
    try {
      const data = await generarReporte(tipo, filtros);
      setReporte(data);
      syncUrl(tipo, filtros);
    } catch (err) {
      setError(err instanceof ApiClientError ? err.message : 'Error al generar reporte');
      setReporte(null);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    if (autoGenerated || !tipos?.length) return;
    if (searchParams.get('tipo') || searchParams.get('auto') === '1') {
      setAutoGenerated(true);
      void handleGenerar(searchParams.get('tipo') || tipoSeleccionado);
    }
    // Solo auto-generar una vez al montar si hay params
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [tipos]);

  const handleExport = async () => {
    try {
      setExporting(true);
      await exportReporteCsv(tipoSeleccionado, buildFiltros());
    } catch (err) {
      alert(err instanceof Error ? err.message : 'Error al exportar');
    } finally {
      setExporting(false);
    }
  };

  const handlePrint = () => {
    if (!reporte) return;
    window.print();
  };

  const handleClearFilters = () => {
    setFechaDesde('');
    setFechaHasta('');
    setAnio(currentYear);
    setEstado('');
    setPagado('');
    setMedioPago('');
    setReporte(null);
    setError('');
    setSearchParams({ tipo: tipoSeleccionado }, { replace: true });
  };

  const selectTipo = (id: string) => {
    setTipoSeleccionado(id);
    setReporte(null);
    setError('');
    setSearchParams({ tipo: id }, { replace: true });
  };

  const showFecha = tipoActual?.filtros.includes('fechaDesde');
  const showAnio = tipoActual?.filtros.includes('anio');
  const showEstado = tipoActual?.filtros.includes('estado');
  const showPagado = tipoActual?.filtros.includes('pagado');
  const showMedio = tipoActual?.filtros.includes('medioPago');

  return (
    <PageListLayout>
      <SpreadsheetShell
        fillHeight
        title="Reportes"
        actions={
          reporte ? (
            <SpreadsheetTitleActions
              onExport={handleExport}
              exporting={exporting}
              exportLabel="Exportar CSV"
              extra={
                <button
                  type="button"
                  onClick={handlePrint}
                  className="inline-flex items-center gap-2 rounded-md px-3 py-1.5 text-sm font-medium text-primary-100 transition-colors hover:bg-primary-800 hover:text-white"
                >
                  <Printer size={16} />
                  Imprimir / PDF
                </button>
              }
            />
          ) : undefined
        }
      >
        <div className="grid min-h-0 flex-1 gap-4 overflow-auto p-4 lg:grid-cols-3">
          <div className="space-y-4 no-print lg:col-span-1">
            <SpreadsheetSection
              title="Tipo de reporte"
              toolbar={
                <SpreadsheetReloadButton onReload={() => refetchTipos()} loading={loadingTipos} />
              }
            >
              <div className="space-y-2 p-3">
                {tipos?.map((tipo) => {
                  const Icon = ICONS[tipo.id] ?? FileBarChart;
                  return (
                    <button
                      key={tipo.id}
                      type="button"
                      onClick={() => selectTipo(tipo.id)}
                      className={`flex w-full items-start gap-3 rounded-md border p-3 text-left transition-colors ${
                        tipoSeleccionado === tipo.id
                          ? 'border-primary-500 bg-primary-50'
                          : 'border-slate-200 hover:bg-slate-50'
                      }`}
                    >
                      <Icon size={18} className="mt-0.5 shrink-0 text-primary-600" />
                      <div>
                        <p className="text-sm font-medium text-slate-800">{tipo.nombre}</p>
                        <p className="text-xs text-slate-500">{tipo.descripcion}</p>
                      </div>
                    </button>
                  );
                })}
              </div>
            </SpreadsheetSection>

            <SpreadsheetSection title="Filtros">
              <div className="space-y-3 p-4">
                <div className="flex items-center gap-2 text-xs font-medium uppercase tracking-wide text-slate-500">
                  <Filter size={13} />
                  Parámetros del período
                </div>

                {showFecha && (
                  <div className="grid gap-2 sm:grid-cols-2">
                    <div>
                      <label className="mb-1 block text-xs font-medium text-slate-600">Desde</label>
                      <input
                        type="date"
                        value={fechaDesde}
                        onChange={(e) => setFechaDesde(e.target.value)}
                        className={`${spreadsheet.filterInput} w-full`}
                      />
                    </div>
                    <div>
                      <label className="mb-1 block text-xs font-medium text-slate-600">Hasta</label>
                      <input
                        type="date"
                        value={fechaHasta}
                        onChange={(e) => setFechaHasta(e.target.value)}
                        className={`${spreadsheet.filterInput} w-full`}
                      />
                    </div>
                  </div>
                )}
                {showAnio && (
                  <div>
                    <label className="mb-1 block text-xs font-medium text-slate-600">Año</label>
                    <input
                      type="number"
                      value={anio}
                      onChange={(e) => setAnio(e.target.value)}
                      className={`${spreadsheet.filterInput} w-full`}
                    />
                    {tipoSeleccionado === 'ejecucion-presupuestaria' && (
                      <p className="mt-1 text-[11px] text-slate-400">
                        Filtra el monto pagado por año. Los saldos del plan son los actuales.
                      </p>
                    )}
                  </div>
                )}
                {showEstado && (
                  <Select
                    label="Estado"
                    value={estado}
                    onChange={(e) => setEstado(e.target.value)}
                    options={ESTADOS}
                  />
                )}
                {showPagado && (
                  <Select
                    label="Estado de pago"
                    value={pagado}
                    onChange={(e) => setPagado(e.target.value)}
                    options={[
                      { value: '', label: 'Todos' },
                      { value: 'true', label: 'Pagados' },
                      { value: 'false', label: 'Pendientes' },
                    ]}
                  />
                )}
                {showMedio && (
                  <Select
                    label="Medio de pago"
                    value={medioPago}
                    onChange={(e) => setMedioPago(e.target.value)}
                    options={MEDIOS}
                  />
                )}

                {error && <Alert type="error">{error}</Alert>}

                <div className="flex flex-col gap-2">
                  <button
                    type="button"
                    onClick={() => handleGenerar()}
                    disabled={loading}
                    className={`${spreadsheet.toolbarBtnPrimary} w-full justify-center`}
                  >
                    <Play size={16} />
                    {loading ? 'Generando...' : 'Generar reporte'}
                  </button>
                  <button
                    type="button"
                    onClick={handleClearFilters}
                    className={`${spreadsheet.toolbarBtn} w-full justify-center`}
                  >
                    <RotateCcw size={15} />
                    Limpiar filtros
                  </button>
                </div>
              </div>
            </SpreadsheetSection>
          </div>

          <div className="lg:col-span-2">
            {reporte ? (
              <div
                ref={printRef}
                className="overflow-hidden rounded-lg border border-slate-300 shadow-sm"
              >
                <ReportPreview reporte={reporte} interactive />
              </div>
            ) : (
              <SpreadsheetSection title="Vista previa">
                <div className="flex min-h-[400px] items-center justify-center p-8">
                  <div className="text-center text-slate-500">
                    <FileBarChart size={48} className="mx-auto mb-4 text-slate-300" />
                    <p className="font-medium text-slate-600">
                      {tipoActual?.nombre ?? 'Seleccione un reporte'}
                    </p>
                    <p className="mt-1 text-sm">
                      Configure los filtros y presione &quot;Generar reporte&quot;
                    </p>
                  </div>
                </div>
              </SpreadsheetSection>
            )}
          </div>
        </div>
      </SpreadsheetShell>
    </PageListLayout>
  );
}
